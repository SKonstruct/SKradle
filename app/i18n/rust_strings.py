#!/usr/bin/env python3
"""Collects the sentences the Rust code passes to `tr(...)` / `tr_args(...)` (see src/i18n.rs) into i18n/rust_strings.cpp,
where lupdate finds them as QT_TRANSLATE_NOOP("rust", ...). Run by update.sh; the generated file is committed."""
import pathlib
import re
import sys

here = pathlib.Path(__file__).resolve().parent
src = here.parent / "src"
CALL = re.compile(r'\btr(?:_args)?\(\s*"')
ESCAPES = {"n": "\n", "t": "\t", '"': '"', "'": "'", "\\": "\\"}


def literal(text: str, start: int) -> str:
    """The Rust string literal whose opening quote ends just before `start`."""
    out = []
    i = start
    while text[i] != '"':
        if text[i] == "\\":
            nxt = text[i + 1]
            if nxt == "\n" or nxt == "\r":  # line continuation: drops the newline and the next line's indent
                i += 2
                while text[i] in " \t\r\n":
                    i += 1
                continue
            out.append(ESCAPES[nxt])
            i += 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


found: dict[str, None] = {}
for path in sorted(src.rglob("*.rs")):
    text = path.read_text(encoding="utf-8")
    # Test modules call tr() with throwaway text; only the code above them counts.
    text = re.split(r"#\[cfg\(test\)\]\s*mod \w+ \{", text)[0]
    text = "\n".join(l for l in text.split("\n") if not l.lstrip().startswith("//"))
    for m in CALL.finditer(text):
        found.setdefault(literal(text, m.end()), None)


def cpp(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


lines = [
    "// Generated by rust_strings.py from the tr(...) calls in src/: do not edit. Keeps the Rust-side sentences in the",
    "// catalogues (context \"rust\"); run update.sh after changing them.",
    "#include <QtCore/QCoreApplication>",
    "",
    "[[maybe_unused]] static const char *const kRustStrings[] = {",
]
lines += [f"    QT_TRANSLATE_NOOP(\"rust\", {cpp(s)})," for s in sorted(found)]
lines += ["};", ""]
out = here / "rust_strings.cpp"
new = "\n".join(lines)
if "--check" in sys.argv:
    sys.exit(0 if out.exists() and out.read_text(encoding="utf-8") == new else 1)
out.write_text(new, encoding="utf-8")
print(f"{len(found)} sentences")
